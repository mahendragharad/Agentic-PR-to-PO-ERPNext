# main.py
import os
import asyncio
import logging
from langchain_mcp_adapters.client import MultiServerMCPClient
from langchain_core.messages import HumanMessage
from src.agents.supervisor import orchestrator_agent_node
from src.agents.tool_identifier import retrieve_relevant_tool_definitions
# from workflow import compile_production_mcp_workflow

def import_json_pretty(data: dict) -> str:
    import json
    return json.dumps(data, indent=2)

async def main():
    if "GROQ_API_KEY" not in os.environ:
        print("❌ Set your GROQ_API_KEY environment variable before running.")
        return

    # 1. Initialize your client to hook directly into the live server endpoint
    client = MultiServerMCPClient({
          "erpnext": {
              "transport": "streamable_http",          # note: underscore here, adapter expects this form
              "url": "http://127.0.0.1:8000/mcp",       # full URL: host + port + mount_path
          }
    })

    print("⏳ Synchronizing schemas dynamically from live ERPNext MCP Server...")
    try:
        # Fetches your live 8 tools dynamically over the HTTP streaming protocol
        live_mcp_tools = await client.get_tools()
        print(f"✅ Loaded {len(live_mcp_tools)} tools from server context loop.")
    except Exception as e:
        print(f"❌ Handshake failed: Check if your server endpoint is active. Details: {e}")
        return

    # # 2. Build the graph pipeline structure using streamed schemas
    # app = compile_production_mcp_workflow(live_mcp_tools)

    # 3. Configure the session thread metadata context mapping
    test_config = {
        "configurable": {
            "thread_id": "production_session_active_01", 
            "tools": live_mcp_tools
        }
    }

    user_query = (
        "can you help me to cancel this purchase order for purchase id po-001011"
    )

    test_state = {
        "messages": [HumanMessage(content=user_query)],
        "retry_counter": {},
        "max_retries": 3,
        "last_error_context": None
    }

    # Execute the Orchestrator node directly in isolation
    node_output = orchestrator_agent_node(test_state, config=test_config)

    tool_output = retrieve_relevant_tool_definitions(user_query=user_query, all_mcp_tools=live_mcp_tools)

    print(tool_output)
        
    # Extract the response message payload generated by Groq
    emitted_msg = node_output["messages"][0]


    print("\n================== ORCHESTRATOR EXTRACTION RESULT ==================")
    if emitted_msg.tool_calls:
        print("🎯 Success! The Orchestrator correctly mapped the intent to an MCP Tool Call.\n")
        for call in emitted_msg.tool_calls:
            print(f"Tool Targeted : {call['name']}")
            print(f"Arguments Generated:\n{import_json_pretty(call['args'])}")
    else:
        print("⚠️ The Orchestrator returned a text response instead of structural tool calls:")
        print(emitted_msg.content)
        print("====================================================================")


if __name__ == "__main__":
    asyncio.run(main())
